import Foundation
import XCTest

@testable import TriCoreDB

/// The exact request each operation added for server 0.1.0-rc.3 sends, read back
/// from a scripted peer. These need no server.
final class OperationsTests: XCTestCase {
    /// One call, the operation it must send, and a response to answer it with.
    private struct Case {
        let name: String
        let op: String
        let reply: String
        let txn: String?
        let call: @Sendable (TriCore) async throws -> Void

        init(
            _ name: String, op: String, reply: String, txn: String?,
            _ call: @escaping @Sendable (TriCore) async throws -> Void
        ) {
            self.name = name
            self.op = op
            self.reply = reply
            self.txn = txn
            self.call = call
        }
    }

    private static func parse(_ text: String) throws -> JSONValue {
        try Frame.decodeBody(Data(text.utf8)) ?? .null
    }

    /// Numbers as doubles, so `1` and `1.0` are the same value as they are on the wire.
    private static func normalized(_ value: JSONValue) -> JSONValue {
        switch value {
        case .int(let number): return .double(Double(number))
        case .array(let items): return .array(items.map(normalized))
        case .object(let members): return .object(members.mapValues(normalized))
        default: return value
        }
    }

    func testEachMethodSendsTheOperationTheServerDeclares() async throws {
        for test in Self.cases {
            let peer = try await ScriptedPeer.start(steps: [
                .response(["request_id": "r1", "status": "ok", "data": try Self.parse(test.reply)])
            ])
            let db = try await peer.connect()
            try await test.call(db)

            let requests = peer.requests
            XCTAssertEqual(requests.count, 1, test.name)
            let request = requests.first ?? .null
            XCTAssertEqual(
                Self.normalized(request["op"] ?? .null), Self.normalized(try Self.parse(test.op)), test.name)
            XCTAssertEqual(request["database"]?.stringValue, "main", test.name)
            XCTAssertEqual(request["options"]?["txn"]?.stringValue, test.txn, test.name)
            await db.close()
            peer.shutdown()
        }
    }

    func testResultsAreDecodedIntoSwiftValues() async throws {
        func reply(_ data: JSONValue) -> ScriptedPeer.Step {
            .response(["request_id": "r", "status": "ok", "data": data])
        }
        let peer = try await ScriptedPeer.start(steps: [
            reply(["Json": ["count": 2, "members": [["member": [97], "score": 1.5], [98]]]]),
            reply(["Json": ["state": "fresh", "valueHex": "009f"]]),
            reply(["CacheValues": [[108], [97]]]),
            reply(["CacheValues": [nil, nil]]),
            reply(["Json": ["results": [["ok": ["CacheValue": [120]]], ["error": "no"]]]]),
        ])
        let db = try await peer.connect()

        let members = try await db.cacheSortedRange("n", "z", start: 0, stop: -1)
        XCTAssertEqual(members, [ScoredMember("a", score: 1.5), ScoredMember(member: Data("b".utf8), score: nil)])
        let fresh = try await db.cacheGetFresh("n", "k", owner: "me", lease: .seconds(1))
        XCTAssertEqual(fresh.value, Data([0x00, 0x9f]))
        let popped = try await db.cacheBlockingLeftPop("n", ["l"], timeout: .milliseconds(10))
        XCTAssertEqual(popped?.key, "l")
        XCTAssertEqual(popped?.value, Data("a".utf8))
        let nothing = try await db.cacheBlockingRightPop("n", ["l"], timeout: .milliseconds(10))
        XCTAssertNil(nothing)
        let results = try await db.cachePipeline([.ping, .ping])
        XCTAssertEqual(results[0].value, Data("x".utf8))
        XCTAssertEqual(results[1].error, "no")
        await db.close()
        peer.shutdown()
    }

    func testAnUnboundedScoreRangeIsSentAsTheLargestFiniteNumber() {
        XCTAssertEqual(ScoreBound.highest.json["value"]?.doubleValue, Double.greatestFiniteMagnitude)
        XCTAssertEqual(ScoreBound.lowest.json["value"]?.doubleValue, -Double.greatestFiniteMagnitude)
    }

